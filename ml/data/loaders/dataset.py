"""PyTorch Dataset implementation for Chest X-Ray data."""

import logging
from collections.abc import Callable
from pathlib import Path

import numpy as np
import pandas as pd
import pydicom
from PIL import Image
from torch.utils.data import Dataset

logger = logging.getLogger(__name__)


class ChestXRayDataset(Dataset):
    """Manifest-backed PyTorch Dataset for Chest X-Ray images.

    This dataset relies on the split manifest generated by Phase 2 preprocessing,
    ensuring deterministic and patient-aware splits are respected.
    """

    def __init__(self, manifest_path: Path, split: str = "train", transform: Callable | None = None) -> None:
        """Initialize the dataset.

        Args:
            manifest_path: Path to the processed CSV manifest.
            split: Which split to load ('train', 'val', or 'test').
            transform: PyTorch/torchvision transforms to apply to the images.
        """
        super().__init__()
        self.manifest_path = manifest_path
        self.split = split
        self.transform = transform

        if not self.manifest_path.exists():
            raise FileNotFoundError(f"Manifest not found at {self.manifest_path}")

        self._load_manifest()

    def _load_manifest(self) -> None:
        """Load and filter the manifest."""
        df = pd.read_csv(self.manifest_path)

        # Ensure we only load valid images for the requested split
        valid_mask = df["validation_status"] == "VALID"
        split_mask = df["split"] == self.split

        self.data = df[valid_mask & split_mask].reset_index(drop=True)

        if len(self.data) == 0:
            logger.warning("Dataset initialized for split '%s' but found 0 valid images.", self.split)
        else:
            logger.info("Loaded %d images for %s split.", len(self.data), self.split)

    def __len__(self) -> int:
        """Return the number of samples in this split."""
        return len(self.data)

    def __getitem__(self, idx: int) -> tuple[Image.Image, int]:
        """Fetch a single sample and its label.

        Returns:
            Tuple of (transformed_image_tensor, class_index).
        """
        row = self.data.iloc[idx]
        image_path = Path(row["original_path"])
        class_index = int(row["class_index"])

        # Handle DICOM or standard image
        if image_path.suffix.lower() == ".dcm":
            dicom = pydicom.dcmread(image_path)
            pixel_array = dicom.pixel_array
            
            # Normalize to 0-255 if needed
            if pixel_array.max() > 255:
                pixel_array = (pixel_array / pixel_array.max() * 255).astype(np.uint8)
            elif pixel_array.dtype != np.uint8:
                pixel_array = pixel_array.astype(np.uint8)
                
            image = Image.fromarray(pixel_array).convert("RGB")
        else:
            # Fallback to normal image loading and convert grayscale to RGB to satisfy 3-channel models
            # like ResNet/DenseNet
            image = Image.open(image_path).convert("RGB")

        if self.transform is not None:
            image = self.transform(image)

        return image, class_index

    def get_metadata(self, idx: int) -> dict:
        """Retrieve metadata for a specific sample. Useful for explainability/debugging."""
        row = self.data.iloc[idx]
        return row.to_dict()
